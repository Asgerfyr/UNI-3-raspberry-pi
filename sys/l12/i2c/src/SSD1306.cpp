// Constructor
SSD1306::SSD1306(const char* i2cDevice, uint8_t i2cAddr) {
  device = i2cDevice;
  address = i2cAddr;
}

// Destructor
SSD1306::~SSD1306() {
    closeI2C();
}

// Open I2C device
int SSD1306::openI2C() {
  fd = open(I2C_DEV, O_RDWR);
  if (fd < 0) {
    perror("open()");
    return -1;
  }
  if (ioctl(fd,I2C_SLAVE, SSD1306_ADDR) < 0) {
    perror("ioctl()");
    return -1;
  }
  return 0;
}

// Close I2C device
void SSD1306::closeI2C() {
  if (fd >= 0)
    close(fd);
}

// Send a single command byte to I2C device
int SSD1306::sendCommand(uint8_t cmd) {
  uint8_t buf[2] = {0x80, cmd};
  ssize_t nbytes = write(fd, buf, sizeof(buf));
  if (nbytes < 0)
    return -1;
  return 0;
}

// Send a single data byte to I2C device
int SSD1306::sendData(uint8_t data) {
  uint8_t buf[2] = {0xC0, data};
  ssize_t nbytes = write(fd, buf, sizeof(buf));
  if (nbytes < 0)
    return -1;
  return 0;
}

// Send a multiple data bytes to I2C device
int SSD1306::sendNData(uint8_t* data, size_t n) {
  uint8_t buf[n+1];
  buf[0] = 0x40;
  for (uint8_t i = 0; i < n; ++i) {
    buf[i+1] = *(data+i);
  }
  ssize_t nbytes = write(fd, buf, n+1);
  if (nbytes < 0)
    return -1;
  return 0;
}

// Initialize OLED screen
int SSD1306::init() {
  // Initialization command sequence
  const uint8_t init_seq[] = {
    0xAE, // Screen Off
    0x8D, // Set charge pump
    0x14, // VCC generated by internal DC/DC circuit
    0xD5, // Set display oscillator frequency
    0x80, // Default
    0xA8, // Set multiplex ratio
    OLED_HEIGHT - 1, // Vertical Size - 1
    0xD3, // 0xD3 Set Display Offset
    0x00, // Default
    0x40,
    0xA0, // Column address 0 is mapped to SEG0
    0xC8, // 0xC0 Set COM output scan direction
    0xDA, // 0xDA Set COM pins hardware configuration
    0x02, // Sequential com config & disable com left/right
    0x81, // 0x81 Set contrast control
    0x01, // Maximum contrast at 0xFF
    0xD9, // Set pre-changed period
    0xF1, // Default
    0xDB, // Set VCOMH Deselected level
    0x40, // Default
    0x20, // Set memory address mode
    0x00, // Horizontal addressing
    0x2E, // Deactive scroll
    0xA4, // Set normal display
    0xA6, // Display follows data in display RAM
    0xAF  // Set display on
  };
  // Send initialization commands one by one
  for (size_t i = 0; i < sizeof(init_seq); ++i) {
    if (sendCommand(init_seq[i]) < 0)
      return -1;
  }
  return 0;
}

// Clear screen
void SSD1306::clear() {
  sendCommand(0x21); // Set column address
  sendCommand(0x00); // Set column start
  sendCommand(0x7F); // Set column address

  sendCommand(0x22); // Set page address
  sendCommand(0x00); // Set page start
  sendCommand(0x03); // Set page end

  uint8_t buf[OLED_WIDTH] = {0x00};
  for (uint8_t row=0; row<OLED_HEIGHT/8; ++row)
    sendNData(buf,sizeof(buf));
}

// Set cursor to (row,column) position
void SSD1306::setCursor(uint8_t row, uint8_t col) {
  sendCommand(0x21); // Set column address
  sendCommand(col); // Set column start
  sendCommand(col); // Set column address

  sendCommand(0x22); // Set page address
  sendCommand(row); // Set page start
  sendCommand(row); // Set page end
}

// Display a single pixel at (x,y) position
int SSD1306::drawPixel(int x, int y, uint8_t* currPixel) {
  if ((x < 0 || x > OLED_WIDTH-1) || (y < 0 || y > OLED_HEIGHT-1))
    return -1;
  uint8_t col = OLED_WIDTH-1-x;
  uint8_t row = y/8;
  uint8_t pixel;
  if (y < 8)
    pixel = *currPixel | 1<<y;
  else if (y >= 8 && y < 16)
    pixel = *currPixel | 1<<(y-8);
  else if (y >= 16 && y < 24)
    pixel = *currPixel | 1<<(y-16);
  else
    pixel = *currPixel | 1<<(y-24);
  *currPixel = pixel;
  setCursor(row,col);
  sendData(pixel);
  return 0;
}

// Clear a single pixel at (x,y) position
int SSD1306::clearPixel(int x, int y, uint8_t* currPixel) {
  if ((x < 0 || x > OLED_WIDTH-1) || (y < 0 || y > OLED_HEIGHT-1))
    return -1;
  uint8_t col = OLED_WIDTH-1-x;
  uint8_t row = y/8;
  uint8_t pixel;
  if (y < 8)
    pixel = *currPixel & !(1<<y);
  else if (y >= 8 && y < 16)
    pixel = *currPixel & !(1<<(y-8));
  else if (y >= 16 && y < 24)
    pixel = *currPixel & !(1<<(y-16));
  else
    pixel = *currPixel & !(1<<(y-24));
  *currPixel = pixel;
  setCursor(row,col);
  sendData(pixel);
  return 0;
}


