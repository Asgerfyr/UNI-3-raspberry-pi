// Display a single character at (x,y) position
int SSD1306::drawChar(int x, int y, char c) {
  if (c < 32 || c > 127)
    return -1;
  uint8_t col = OLED_WIDTH-1-x;
  uint8_t row = y/8;
  uint8_t ch[6];
  for (uint8_t i=0; i<6; ++i)
    ch[i] = font6x8[c-32][i];
  for (uint8_t i=0; i<6; ++i) {
    setCursor(row,col-i);
    sendData(ch[i]);
  }
  return 0;
}

// Display a string at (x,y) position
int SSD1306::drawString(int x, int y, const std::string& str) {
  for (char c : str) {
    drawChar(x,y,c);
    x += 6;
    if (x > 120)
      break;
  }
  return 0;
}
